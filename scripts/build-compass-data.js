#!/usr/bin/env node
/* =============================================================================
 * Build the country data for Compass (compass.html): js/compass-countries.js
 *
 *   curl -L -o population.csv https://raw.githubusercontent.com/datasets/population/main/data/population.csv
 *   npm install --no-save world-countries@5
 *   node scripts/build-compass-data.js population.csv
 *
 * Sources
 *   - Country facts (name, capital, region, subregion, lat/lng): mledoze/countries
 *     ("world-countries" on npm, ODbL 1.0), the dataset REST Countries is built on.
 *   - Population: World Bank, SP.POP.TOTL (CC BY 4.0), as packaged by
 *     github.com/datasets/population. The latest year each country has is used.
 *
 * Countries: the 193 UN members plus the two UN observer states (Vatican City,
 * Palestine) = 195, the same set as Outline. All of them can be the answer.
 * ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');

let countries;
try { countries = require('world-countries'); } catch (e) {
  console.error('Missing dependency. Run:\n  npm install --no-save world-countries@5');
  process.exit(1);
}
const csvPath = process.argv[2];
if (!csvPath || !fs.existsSync(csvPath)) {
  console.error('Pass the World Bank population CSV. See the comment at the top of this file.');
  process.exit(1);
}

const OUT = path.join(__dirname, '..', 'js', 'compass-countries.js');
const OBSERVERS = new Set(['VA', 'PS']);
// Not in the World Bank tables: Vatican City (Holy See estimate).
const POPULATION_FALLBACK = { VAT: 825 };
// Subregion names that would read the same as the continent.
const SUBREGION_FIXES = { 'North America': 'Northern America' };
// Extra names people type that the dataset lacks.
const EXTRA_ALIASES = { US: ['US'], GB: ['UK', 'Britain'], CZ: ['Czech Republic'], TR: ['Turkey'], CV: ['Cape Verde'] };

/** Other names a player might type: Latin-script alternative spellings, acronyms like USA. */
function aliasesOf(c) {
  const seen = new Set([c.name.common.toLowerCase()]);
  const out = [];
  [c.name.official].concat(c.altSpellings || [], EXTRA_ALIASES[c.cca2] || []).forEach((a) => {
    if (!a || a.includes(',') || a.length > 40 || !/^[A-Za-z\u00C0-\u024F' .()-]+$/.test(a)) return;
    if (a.length < 3 && !(EXTRA_ALIASES[c.cca2] || []).includes(a)) return;   // skip ISO codes
    if (seen.has(a.toLowerCase())) return;
    seen.add(a.toLowerCase());
    out.push(a);
  });
  return out.join('|');
}

/* ------------------------------------------------------------- population */
function parseCsvLine(line) {
  const out = []; let cur = '', q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) { if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (ch === '"') q = false; else cur += ch; }
    else if (ch === '"') q = true; else if (ch === ',') { out.push(cur); cur = ''; } else cur += ch;
  }
  out.push(cur);
  return out;
}
const latest = {};   // ISO3 -> { year, value }
fs.readFileSync(csvPath, 'utf8').split(/\r?\n/).slice(1).forEach((line) => {
  if (!line.trim()) return;
  const [, code, year, value] = parseCsvLine(line);
  const y = Number(year), v = Number(value);
  if (!code || !Number.isFinite(y) || !(v > 0)) return;
  if (!latest[code] || y > latest[code].year) latest[code] = { year: y, value: v };
});

/* --------------------------------------------------------------- countries */
function continentOf(c) {
  if (c.region === 'Americas') return c.subregion === 'South America' ? 'South America' : 'North America';
  return c.region; // Africa, Asia, Europe, Oceania
}
const missing = [];
const rows = countries
  .filter((c) => c.unMember || OBSERVERS.has(c.cca2))
  .map((c) => {
    const pop = latest[c.cca3] ? latest[c.cca3].value : POPULATION_FALLBACK[c.cca3];
    if (!pop) missing.push(c.cca3);
    return [
      c.name.common, c.cca2, (c.capital && c.capital[0]) || '',
      continentOf(c), SUBREGION_FIXES[c.subregion] || c.subregion || continentOf(c),
      Math.round(pop || 0),
      Math.round(c.latlng[0] * 100) / 100, Math.round(c.latlng[1] * 100) / 100,
      aliasesOf(c)
    ];
  })
  .sort((a, b) => a[0].localeCompare(b[0], 'en'));
if (missing.length) { console.error('No population for: ' + missing.join(', ')); process.exit(1); }

const years = {};
countries.forEach((c) => { if (latest[c.cca3]) years[latest[c.cca3].year] = (years[latest[c.cca3].year] || 0) + 1; });

const header = `/* Generated by scripts/build-compass-data.js. Do not edit by hand.
 * Country facts: mledoze/countries (ODbL 1.0). Population: World Bank SP.POP.TOTL (CC BY 4.0).
 * Row format: [name, cca2, capital, continent, subregion, population, lat, lng, aliases ('|'-separated)].
 */
`;
fs.writeFileSync(OUT, header + 'window.COMPASS_COUNTRIES = ' + JSON.stringify(rows) + ';\n');
console.log(`Wrote ${rows.length} countries to ${path.relative(process.cwd(), OUT)} (${fs.statSync(OUT).size} bytes).`);
console.log('Population years used:', JSON.stringify(years));
